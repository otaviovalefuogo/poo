    private java.util.List<String>
    fatiarExpressao(String expressao) {
        java.util.List<String>
        lista = new java.util.ArrayList<>();
        String numeroTemporario = "";


        for (int i = 0; i < expressao.length(); i++) {
            char caractere = expressao.charAt(i);


            if (Character.isDigit(caractere)) {
                numeroTemporario = numeroTemporario + caractere; 
            } else {
             
                
                
                if (!numeroTemporario.isEmpty()) {
                    lista.add(numeroTemporario); 
                    numeroTemporario = ""; 
                }
                
       
                lista.add(String.valueOf(caractere));
            }
        }
        
   
        if (!numeroTemporario.isEmpty()) {
            lista.add(numeroTemporario);
        }

        return lista;
    }
    
    private int precedencia(String operador) {
        if (operador.equals("+") || operador.equals("-")) {
            return 1; 
        } else if (operador.equals("*") || operador.equals("/")) {
            return 2; 
        }
        return 0;
    }
    private java.util.List<String>
        organizar(java.util.List<String> listar) {
        
        java.util.List<String> filaSaida = new java.util.ArrayList<>();
        java.util.Stack<String> pilhaOperadores = new java.util.Stack<>();

        for (int i = 0; i < listar.size(); i++) {
            String lista = listar.get(i);

      
            if (Character.isDigit(lista.charAt(0))) {
                filaSaida.add(lista);
            } else {
               
                while (!pilhaOperadores.isEmpty() && precedencia(pilhaOperadores.peek()) >= precedencia(lista)) {
                  
                    filaSaida.add(pilhaOperadores.pop());
                }
              
                pilhaOperadores.push(lista);
            }
        }

 
        while (!pilhaOperadores.isEmpty()) {
            filaSaida.add(pilhaOperadores.pop());
        }

        return filaSaida;
    }
      
    private double calcularPfixa(java.util.List<String> pfixa) {
        
  
        java.util.Stack<Double> 
        pilhaMatematica = new java.util.Stack<>();

        for (int i = 0; i < pfixa.size(); i++) {
            String token = pfixa.get(i);

            
            if (Character.isDigit(token.charAt(0))) {
                pilhaMatematica.push(Double.parseDouble(token));
            } else {
               
                double numero2 = pilhaMatematica.pop(); 
                double numero1 = pilhaMatematica.pop(); 
                double resultado = 0;

                if (token.equals("+")) {
                    resultado = numero1 + numero2;
                } else if (token.equals("-")) {
                    resultado = numero1 - numero2;
                } else if (token.equals("*")) {
                    resultado = numero1 * numero2;
                } else if (token.equals("/")) {
                    resultado = numero1 / numero2;
                }
                pilhaMatematica.push(resultado);
            }
        }
        return pilhaMatematica.pop();
    }
    

    
    

